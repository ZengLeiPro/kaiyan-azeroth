-- Register WebEvent model (web_analytics.events) —— 占位 migration（IF NOT EXISTS 空跑）
--
-- 生产 RDS：events 表由 collector（独立 analytics collector）的
-- bootstrap.sql 维护，已存在为月分区表（PARTITION BY RANGE(received_at)，
-- 主键 (id, received_at)，5 个组合索引）。本 migration 在生产 RDS 上全部
-- IF NOT EXISTS 空跑，仅用于：
--   1. 让 Prisma 的 _prisma_migrations 表记录此 model 已"注册"，**阻止未来
--      在 ky-azeroth 仓库跑 `prisma migrate dev` 时 Prisma 自动生成 CREATE
--      TABLE web_analytics.events 的迁移**——下次 deploy 会因表已存在冲突；
--   2. 本地 dev DB（如有人需要完整 schema 同步测试）自动建一张**普通表
--      （无分区）**兜底，让 prisma client 至少能查空表。
--
-- ⚠ 不要在此修改字段结构——分区 / 字段 / 索引的 SOT 是 collector 的
-- `sql/bootstrap.sql`；此处任何字段变更必须先改 bootstrap.sql 并迁移生产，
-- 否则下次 prisma migrate dev 会检测到 drift 误生成迁移。
--
-- 字段差异说明：collector bootstrap.sql 用 `GENERATED ALWAYS AS IDENTITY`，
-- 这里用 `GENERATED BY DEFAULT AS IDENTITY` 对齐 Prisma `@default(autoincrement())`
-- 行为（仅影响本地 dev DB；生产 IF NOT EXISTS 跳过）。

CREATE SCHEMA IF NOT EXISTS "web_analytics";

CREATE TABLE IF NOT EXISTS "web_analytics"."events" (
  "id"           BIGINT GENERATED BY DEFAULT AS IDENTITY,
  "received_at"  TIMESTAMPTZ NOT NULL DEFAULT now(),
  "client_ts"    TIMESTAMPTZ,
  "site"         TEXT NOT NULL,
  "event"        TEXT NOT NULL,
  "vid"          TEXT,
  "sid"          TEXT,
  "path"         TEXT,
  "page_type"    TEXT,
  "title"        TEXT,
  "referrer"     TEXT,
  "ref_host"     TEXT,
  "utm_source"   TEXT,
  "utm_medium"   TEXT,
  "utm_campaign" TEXT,
  "utm_term"     TEXT,
  "utm_content"  TEXT,
  "placement"    TEXT,
  "channel"      TEXT,
  "label"        TEXT,
  "ua"           TEXT,
  "is_bot"       BOOLEAN NOT NULL DEFAULT false,
  "ip_hash"      TEXT,
  "screen"       TEXT,
  "lang"         TEXT,
  "raw"          JSONB,
  PRIMARY KEY ("id", "received_at")
);

CREATE INDEX IF NOT EXISTS "events_received_at_idx"
  ON "web_analytics"."events" ("received_at");

CREATE INDEX IF NOT EXISTS "events_event_received_at_idx"
  ON "web_analytics"."events" ("event", "received_at");

CREATE INDEX IF NOT EXISTS "events_path_received_at_idx"
  ON "web_analytics"."events" ("path", "received_at");

CREATE INDEX IF NOT EXISTS "events_vid_received_at_idx"
  ON "web_analytics"."events" ("vid", "received_at");

CREATE INDEX IF NOT EXISTS "events_sid_received_at_idx"
  ON "web_analytics"."events" ("sid", "received_at");
