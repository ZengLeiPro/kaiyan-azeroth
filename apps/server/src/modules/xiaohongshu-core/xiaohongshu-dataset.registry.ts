export type XiaohongshuDatasetPagination = IXiaohongshuDatasetDefinition['pagination'];

export interface XiaohongshuDatasetRegistryEntry {
  id: string;
  label: string;
  group: XiaohongshuDatasetGroup;
  description: string;
  requiredScope?: string;
  endpoint?: string;
  method?: 'GET' | 'POST';
  source: 'official_api' | 'local_report';
  availability?: XiaohongshuDatasetAvailability;
  availabilityReason?: string;
  requiredParams?: string[];
  pagination?: XiaohongshuDatasetPagination;
  supportsDateRange?: boolean;
  supportsDataCaliber?: boolean;
  defaults?: Record<string, XiaohongshuJsonValue>;
  itemPaths?: string[];
  totalPaths?: string[];
  aggregationPaths?: string[];
  coreFields?: string[];
}

const localReport = (
  id: string,
  label: string,
  description: string,
  level: string,
  coreFields: string[]
): XiaohongshuDatasetRegistryEntry => ({
  id,
  label,
  group: 'report',
  description,
  requiredScope: 'report_service',
  source: 'local_report',
  pagination: 'page',
  supportsDateRange: true,
  supportsDataCaliber: true,
  defaults: { level },
  coreFields,
});

const api = (
  entry: Omit<XiaohongshuDatasetRegistryEntry, 'source'>
): XiaohongshuDatasetRegistryEntry => {
  const availabilityReason =
    entry.availabilityReason ??
    (entry.availability === 'requires_context'
      ? '需要从具体对象进入并填写官方接口要求的上下文参数'
      : entry.availability === 'role_unsupported'
        ? '只对特定代理商/服务商账户角色开放，需按当前授权角色探测'
        : undefined);
  return {
    method: 'POST',
    pagination: 'page',
    requiredParams: [],
    itemPaths: ['data_list', 'list', 'items', 'records'],
    totalPaths: ['total_count', 'total', 'page.total_count', 'page.total'],
    coreFields: [],
    ...entry,
    availabilityReason,
    source: 'official_api',
  };
};

